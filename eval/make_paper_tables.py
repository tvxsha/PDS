def macro(name, value):
    return "\\newcommand{\\" + name + "}{" + value + "}"


def numbers(cfg, stats, seeds_data, latency):
    lines = ["% generated by eval/make_paper_tables.py - do not edit by hand"]
    for i, sd in enumerate(seeds_data):
        L = SEED_LETTERS[i]
        y = sd["y"]
        lines += [macro(f"resSeed{L}", str(sd["seed"])), macro(f"resNPos{L}", str(int(y.sum()))),
                  macro(f"resNNeg{L}", str(int((1 - y).sum()))), macro(f"resHash{L}", sd["hash"])]
    for m in cfg["methods"]:
        c = CODES.get(m)
        if c is None:
            continue
        for b in cfg["budgets"]:
            per = [s[(m, b)] for s in stats]
            W = word(b)
            tp, fp = [p["tpr"] for p in per], [p["fpr"] for p in per]
            lines += [macro(f"resTPR{W}{c}", f2(mean(tp))), macro(f"resTPRmin{W}{c}", f2(lo(tp))), macro(f"resTPRmax{W}{c}", f2(hi(tp))),
                      macro(f"resTPRlo{W}{c}", f2(mean([p["tpr_lo"] for p in per]))), macro(f"resTPRhi{W}{c}", f2(mean([p["tpr_hi"] for p in per]))),
                      macro(f"resFPR{W}{c}", f3(mean(fp)))]
            for p in cfg["prevalences"]:
                v = mean([q["prec"][p] for q in per])
                lines.append(macro(f"resPrec{W}{c}Prev{word(p)}", ptex(v)))
    if latency:
        for stage, (med, p95) in latency.items():
            c = STAGE_CODES[stage]
            lines.append(macro(f"resLatMed{c}", f"{med:.1f}"))
            if p95 is not None:
                lines.append(macro(f"resLatPNinetyFive{c}", f"{p95:.1f}"))
    return "\n".join(lines) + "\n"


def summary(cfg, stats, seeds_data, mode):
    out = {"mode": mode, "seeds": [sd["seed"] for sd in seeds_data], "split_hashes": [sd["hash"] for sd in seeds_data],
           "n_eval": [int(len(sd["y"])) for sd in seeds_data], "n_poisoned": [int(sd["y"].sum()) for sd in seeds_data],
           "budgets": cfg["budgets"], "prevalences": cfg["prevalences"], "methods": {}}
    for m in cfg["methods"]:
        out["methods"][m] = {}
        for b in cfg["budgets"]:
            per = [s[(m, b)] for s in stats]
            out["methods"][m][str(b)] = {
                "tpr_per_seed": [p["tpr"] for p in per], "fpr_per_seed": [p["fpr"] for p in per],
                "tpr_mean": mean([p["tpr"] for p in per]), "fpr_mean": mean([p["fpr"] for p in per]),
                "tpr_ci_per_seed": [[p["tpr_lo"], p["tpr_hi"]] for p in per],
                "precision_mean": {str(p): mean([q["prec"][p] for q in per]) for p in cfg["prevalences"]}}
    return out


# --------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(description="Paper tables from the final run (see the top of this file).")
    ap.add_argument("--final", action="store_true", help="read the held-out files (final_test_*); default is the dry run")
    ap.add_argument("--out", default=OUT_DIR)
    ap.add_argument("--latency", default=LATENCY)
    args = ap.parse_args()

    cfg, _ = final_test.load_config()
    role = final_test.HELD_OUT if args.final else "val"
    mode = final_test.MODES[role]
    prefix = f"final_{mode}"
    mark = "" if args.final else "[DRY RUN on validation, not results] "
    seeds_data = [load_seed(s, prefix, cfg["methods"]) for s in cfg["seeds"]]
    stats = [seed_stats(sd, cfg) for sd in seeds_data]

    first = seeds_data[0]
    y0, g0, a0 = first["y"], first["srcg"], first["atk"]
    counts = {g: (int(((g0 == g) & (y0 == 1)).sum()), int(((g0 == g) & (y0 == 0)).sum())) for g in sorted(set(g0))}
    attack_n = {a: int(((a0 == a) & (y0 == 1)).sum()) for a in sorted(set(a0[y0 == 1]))}
    n_note = ("Evaluation documents per seed: " + ", ".join(f"{int(len(sd['y']))} ({int(sd['y'].sum())} poisoned)" for sd in seeds_data) + ".")

    os.makedirs(args.out, exist_ok=True)
    files = {"tab_headline.tex": t_headline(cfg, stats, mark, n_note), "tab_precision.tex": t_precision(cfg, stats, mark),
             "tab_source.tex": t_source(cfg, stats, mark, counts), "tab_attack.tex": t_attack(cfg, stats, mark, attack_n)}

    latency = None
    if os.path.exists(args.latency):
        files["tab_latency.tex"] = t_latency(args.latency, mark)
        from eval import cascade_eval
        ms, _, p95, _ = cascade_eval.read_latency(args.latency)
        latency = {s: (ms[s], p95.get(s)) for s in ms}
    else:
        print(f"note: {args.latency} does not exist, so there is no latency table (task 1.3).")

    cascade_paths = [os.path.join(RESULTS_DIR, f"{prefix}_seed{s}_cascade.csv") for s in cfg["seeds"]]
    if all(os.path.exists(p) for p in cascade_paths):
        files["tab_cascade.tex"] = t_cascade([pd.read_csv(p) for p in cascade_paths], mark)
    else:
        print("note: the cascade files are missing (the 'cascade' extra was not in eval/final_config.json), so there is no cascade table.")

    files["numbers.tex"] = numbers(cfg, stats, seeds_data, latency)
    files["summary.json"] = json.dumps(summary(cfg, stats, seeds_data, mode), indent=1) + "\n"
    for name, text in files.items():
        with open(os.path.join(args.out, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("Wrote to " + args.out + ":", *sorted(files), sep="\n  ")
    if not args.final:
        print("\nDRY RUN: validation numbers, captions are marked. Use --final after the freeze and the three test runs.")


if __name__ == "__main__":
    main()