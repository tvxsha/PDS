def t_headline(cfg, stats, mark, n_note):
    budgets = cfg["budgets"]
    header = "Method & " + " & ".join(f"TPR @ {pct(b)}\\% & FPR @ {pct(b)}\\%" for b in budgets)
    rows = []
    for m in cfg["methods"]:
        cells = []
        for b in budgets:
            per = [s[(m, b)] for s in stats]
            cells.append(f"{f2(mean([p['tpr'] for p in per]))} [{f2(mean([p['tpr_lo'] for p in per]))}, "
                         f"{f2(mean([p['tpr_hi'] for p in per]))}]")
            cells.append(f3(mean([p["fpr"] for p in per])))
        rows.append(tex(DISPLAY.get(m, m)) + " & " + " & ".join(cells) + r" \\")
    cap = ("Recall (TPR) and realised false-alarm rate (FPR) at each false-alarm budget, mean over seeds. Brackets: mean of the "
           "per-seed 95\\% group-bootstrap intervals. Thresholds come from the training split only. " + n_note)
    return table(cap, "tab:headline", "@{}l" + "cc" * len(budgets) + "@{}", header, rows, mark)


def t_precision(cfg, stats, mark):
    budgets, prevs = cfg["budgets"], cfg["prevalences"]
    cols = [(b, p) for b in budgets for p in prevs]
    header = "Method & " + " & ".join(f"{pct(b)}\\% budget, {pct(p)}\\% poisoned" for b, p in cols)
    rows = []
    for m in cfg["methods"]:
        cells = [ptex(mean([s[(m, b)]["prec"][p] for s in stats])) for b, p in cols]
        rows.append(tex(DISPLAY.get(m, m)) + " & " + " & ".join(cells) + r" \\")
    cap = ("Precision of an alert when the stated share of documents is poisoned, mean over seeds. Computed from the recall and "
           "false-alarm rate in Table~\\ref{tab:headline}, not measured on a stream; a zero observed false-alarm rate is replaced by "
           "the rule-of-three bound.")
    return table(cap, "tab:precision", "@{}l" + "c" * len(cols) + "@{}", header, rows, mark)


def t_source(cfg, stats, mark, counts):
    budgets = cfg["budgets"]
    sources = sorted({g for s in stats for p in s.values() for g in p["source"]}, key=lambda g: (SRC_GROUPS + [g]).index(g))
    methods = [m for m in FOCUS if m in cfg["methods"]]
    header = "Method & " + " & ".join(tex(g) for g in sources)
    rows = []
    for k, b in enumerate(budgets):
        if k:
            rows.append(r"\midrule")
        rows.append(r"\multicolumn{" + str(len(sources) + 1) + r"}{@{}l}{\textit{Budget " + pct(b) + r"\%: TPR / FPR}} \\")
        for m in methods:
            cells = []
            for g in sources:
                t = mean([s[(m, b)]["source"].get(g, (float("nan"), float("nan")))[0] for s in stats])
                f = mean([s[(m, b)]["source"].get(g, (float("nan"), float("nan")))[1] for s in stats])
                cells.append(f"{f2(t)} / {f2(f)}")
            rows.append(tex(DISPLAY.get(m, m)) + " & " + " & ".join(cells) + r" \\")
    sizes = ", ".join(f"{tex(g)} {counts[g][0]} poisoned / {counts[g][1]} clean" for g in sources if g in counts)
    cap = ("Recall and false-alarm rate by source, mean over seeds. Documents per source in the first seed: " + sizes + ".")
    return table(cap, "tab:source", "@{}l" + "c" * len(sources) + "@{}", header, rows, mark)


def t_attack(cfg, stats, mark, first_counts):
    b = cfg["budgets"][0]
    methods = [m for m in FOCUS if m in cfg["methods"]]
    types = sorted({a for s in stats for p in s.values() for a in p["attack"]})
    header = "Attack type & $n$ & " + " & ".join(tex(DISPLAY.get(m, m)) for m in methods)
    rows = []
    for a in types:
        cells = [f2(mean([s[(m, b)]["attack"].get(a, float("nan")) for s in stats])) for m in methods]
        rows.append(tex(a) + f" & {first_counts.get(a, 0)} & " + " & ".join(cells) + r" \\")
    cap = (f"Recall among poisoned documents by attack type at the {pct(b)}\\% budget, mean over seeds ($n$ = poisoned documents of "
           "that type in the first seed).")
    return table(cap, "tab:attack", "@{}lr" + "c" * len(methods) + "@{}", header, rows, mark)


def read_latency_table(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    det = data.get("detectors")
    if not isinstance(det, dict) or not det:
        raise SystemExit(f"{path} has no 'detectors' object.")
    hw = data.get("hardware")
    hardware = "; ".join(f"{k}: {v}" for k, v in hw.items() if isinstance(v, (str, int, float))) if isinstance(hw, dict) else ""
    return det, hardware, data.get("n")


def t_latency(path, mark):
    det, hardware, n = read_latency_table(path)
    rows = []
    for name, e in det.items():
        rows.append(tex(name) + " & " + " & ".join(f"{e[k]:.1f}" if isinstance(e.get(k), (int, float)) else "n/a"
                                                  for k in ("median_ms", "p95_ms", "mean_ms")) + r" \\")
    cap = (f"Latency per document in milliseconds ({n} documents, one document at a time). " + (tex(hardware) + "." if hardware else ""))
    return table(cap, "tab:latency", "@{}lrrr@{}", "Detector & median & p95 & mean", rows, mark)


def t_cascade(frames, mark):
    allf = pd.concat(frames, ignore_index=True)
    b = float(allf["budget"].min()) if allf["budget"].nunique() == 1 else 0.05
    sub = allf[np.isclose(allf["budget"].astype(float), b)].copy()
    sub["qkey"] = [-1.0 if (v != v or v == "") else float(v) for v in sub["q"]]       # designs without a q (empty or NaN) -> -1
    order = list(dict.fromkeys(zip(sub["design"], sub["qkey"])))
    rows = []
    for design, q in order:
        part = sub[(sub["design"] == design) & (sub["qkey"] == q)]
        rows.append(tex(design) + " & " + " & ".join([f2(part["tpr"].mean()), f3(part["fpr"].mean()), f"{part['ms_clean'].mean():.1f}",
                                                      f"{part['ms_poisoned'].mean():.1f}",
                                                      f"{part['saving_clean'].mean() * 100:.0f}\\%"]) + r" \\")
    cap = (f"Cascade designs at the {pct(b)}\\% budget, mean over seeds: recall, false-alarm rate, typical (median-cost) milliseconds per clean and  "
           "per poisoned document, and the saving on clean traffic against running every detector. Costs are per-detector medians from the latency benchmark; mean costs are higher because of a long-document tail.")
    return table(cap, "tab:cascade", "@{}lccrrr@{}", r"Design & TPR & FPR & ms clean & ms poisoned & saving", rows, mark)


