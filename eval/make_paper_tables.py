"""
Paper tables and numbers from the one-shot final run (roadmap task N4, reduced to what the paper needs).

    python -m eval.make_paper_tables            # reads the DRY-RUN files (final_dryrun_*): captions say "not results"
    python -m eval.make_paper_tables --final    # reads the held-out files (final_test_*): the numbers for the paper

It reads, for every seed of eval/final_config.json,
    eval/results/final_<mode>_seed<N>_scores.csv        (one score per document and method)
    eval/results/final_<mode>_seed<N>_thresholds.json   (the TRAIN thresholds that were applied)
    eval/results/final_<mode>_seed<N>_cascade.csv       (only if the cascade extra was run)
    eval/results/latency_benchmark.json                 (only if it exists)
and recomputes TPR, FPR, precision and the group-bootstrap intervals with the same functions as eval.final_test, so the
numbers equal the ones in final_<mode>_seed<N>.md. Nothing is fitted and no document is scored here.

Files written to paper/tables/ (or --out):
    tab_headline.tex   recall and realised false-alarm rate at every budget, all methods
    tab_precision.tex  precision at the stated shares of poisoned documents
    tab_source.tex     recall / false-alarm rate by source
    tab_attack.tex     recall by attack type (first budget)
    tab_latency.tex    median / p95 / mean milliseconds (only if the latency file exists)
    tab_cascade.tex    cascade designs (only if the cascade files exist)
    numbers.tex        \\newcommand macros for the numbers the text quotes (so text and tables cannot disagree)
    summary.json       the same numbers, per seed and averaged, for the number check of the paper

Seeds share most of their documents, so the "range over seeds" is a stability check, not a confidence interval; the
bracket in the headline table is the mean of the per-seed 95% group-bootstrap interval.
"""

import argparse
import json
import os

import numpy as np
import pandas as pd

from eval import final_test
from eval.fpr_eval import SRC_GROUPS, group_bootstrap, precision, source_group

RESULTS_DIR = final_test.RESULTS_DIR
OUT_DIR = "paper/tables"
LATENCY = os.path.join(RESULTS_DIR, "latency_benchmark.json")

DISPLAY = {"pattern bank": "Pattern bank", "embedding": "Embedding", "perplexity": "Perplexity",
           "naive average of the 3": "Naive average (3)", "sentence classifier": "Sentence classifier",
           "LR on the 3 current scores": "LR (3 scores)", "LR + sentence classifier": "LR + sentence",
           "published classifier": "Published classifier"}
CODES = {"pattern bank": "Pat", "embedding": "Emb", "perplexity": "Ppl", "naive average of the 3": "Avg",
         "sentence classifier": "Sen", "LR on the 3 current scores": "LRthree", "LR + sentence classifier": "LRsen",
         "published classifier": "Pub"}
FOCUS = ["pattern bank", "embedding", "perplexity", "sentence classifier", "LR + sentence classifier", "published classifier"]
WORDS = {0.05: "Five", 0.01: "One", 0.001: "Tenth"}           # 5 %, 1 %, 0.1 % in macro names (letters only)
SEED_LETTERS = "ABCDEFGH"
STAGE_CODES = {"pattern": "Pat", "sentence": "Sen", "embedding": "Emb", "perplexity": "Ppl", "published": "Pub"}


# --------------------------------------------------------------------------
# small helpers
# --------------------------------------------------------------------------

def tex(s):
    return str(s).replace("\\", " ").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def pct(p):
    return f"{p * 100:g}"


def word(x):
    if x not in WORDS:
        raise SystemExit(f"No macro word for the value {x} (known: {sorted(WORDS)}). Add it to WORDS in eval/make_paper_tables.py.")
    return WORDS[x]


def mean(xs):
    xs = [x for x in xs if x == x]
    return float(np.mean(xs)) if xs else float("nan")


def lo(xs):
    xs = [x for x in xs if x == x]
    return float(min(xs)) if xs else float("nan")


def hi(xs):
    xs = [x for x in xs if x == x]
    return float(max(xs)) if xs else float("nan")


def f2(x):
    return "n/a" if x != x else f"{x:.2f}"


def f3(x):
    return "n/a" if x != x else f"{x:.3f}"


def ptex(p):
    """precision (0..1) as a LaTeX percentage"""
    if p != p:
        return "n/a"
    return (f"{p * 100:.1f}" if p >= 0.01 else f"{p * 100:.2f}") + r"\%"


def rate(flags, mask):
    return float(flags[mask].mean()) if mask.any() else float("nan")


def table(caption, label, colspec, header, rows, mark):
    out = ["% generated by eval/make_paper_tables.py - do not edit by hand"]
    if mark:
        out.append("% DRY RUN on the validation split: these are NOT results")
    out += [r"\begin{table}[t]", r"\caption{" + mark + caption + "}", r"\label{" + label + "}", r"\centering", r"\footnotesize",
            r"\resizebox{\columnwidth}{!}{%", r"\begin{tabular}{" + colspec + "}", r"\toprule", header + r" \\", r"\midrule"]
    out += rows
    out += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    return "\n".join(out) + "\n"


