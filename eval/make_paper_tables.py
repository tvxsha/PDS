# reading one seed
# --------------------------------------------------------------------------

def load_seed(seed, prefix, methods):
    scores_path = os.path.join(RESULTS_DIR, f"{prefix}_seed{seed}_scores.csv")
    thr_path = os.path.join(RESULTS_DIR, f"{prefix}_seed{seed}_thresholds.json")
    for p in (scores_path, thr_path):
        if not os.path.exists(p):
            raise SystemExit(f"{p} does not exist. Run:  python -m eval.final_test --seed {seed} "
                             + ("--final" if prefix.startswith("final_test") else "--dry-run"))
    df = pd.read_csv(scores_path, dtype={"id": str})
    with open(thr_path, encoding="utf-8") as f:
        meta = json.load(f)
    thr = meta["thresholds"]
    first = df[df["method"] == methods[0]].reset_index(drop=True)
    if first.empty:
        raise SystemExit(f"{scores_path} has no rows for the method {methods[0]!r}.")
    ids = first["id"]
    by_method = {}
    for m in methods:
        sub = df[df["method"] == m].set_index("id")["score"]
        if m not in thr:
            raise SystemExit(f"{thr_path} has no thresholds for {m!r}.")
        if len(sub) != len(ids) or not sub.index.is_unique or set(sub.index) != set(ids):
            raise SystemExit(f"{scores_path}: method {m!r} does not cover the same documents as {methods[0]!r}.")
        by_method[m] = sub.reindex(ids).to_numpy(dtype=float)
    return {"seed": seed, "hash": meta.get("split_hash", ""), "role": meta.get("role", ""),
            "y": first["label"].to_numpy(dtype=int), "grp": first["group"].astype(str).to_numpy(),
            "srcg": np.array([source_group(s) for s in first["source"].astype(str)]),
            "atk": first["attack_type"].astype(str).to_numpy(), "scores": by_method, "thr": thr}


def seed_stats(sd, cfg):
    """{(method, budget): {...}} for one seed; the intervals are the ones of the report (group bootstrap)."""
    y, grp, srcg, atk = sd["y"], sd["grp"], sd["srcg"], sd["atk"]
    n_neg = int((1 - y).sum())
    out = {}
    for m in cfg["methods"]:
        for b in cfg["budgets"]:
            t = sd["thr"][m][str(b)]
            fl = sd["scores"][m] > t
            tpr, fpr = rate(fl, y == 1), rate(fl, y == 0)
            (tl, th), (fl_lo, fl_hi) = group_bootstrap(fl, y, grp, reps=cfg["bootstrap_reps"])
            out[(m, b)] = {
                "tpr": tpr, "fpr": fpr, "tpr_lo": float(tl), "tpr_hi": float(th), "fpr_lo": float(fl_lo), "fpr_hi": float(fl_hi),
                "prec": {p: precision(tpr, fpr, p, n_neg) for p in cfg["prevalences"]},
                "source": {g: (rate(fl, (srcg == g) & (y == 1)), rate(fl, (srcg == g) & (y == 0))) for g in sorted(set(srcg))},
                "attack": {a: rate(fl, (atk == a) & (y == 1)) for a in sorted(set(atk[y == 1]))},
            }
    return out


