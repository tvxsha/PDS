"""
Pool every source into one file (roadmap task 2.6).

    python -m data.pool_datasets                       # default sources
    python -m data.pool_datasets --sources pds,bipia   # subset
    python -m data.pool_datasets --beir-zip C:\\path\\nq.zip

Writes
    data/pooled/pooled.jsonl   (git-ignored: contains other people's data)
    data/pooled_stats.md       (committed: counts, lengths, shortcut check)

A source that fails to load (no internet, missing library, gated dataset) is
SKIPPED with a message, not fatal, so you can build the pool incrementally.
"""

import argparse
import os
from collections import Counter, defaultdict

from data.loaders.clean_sampler import length_summary
from eval.protocol import POOLED_PATH, print_source_counts, write_jsonl

STATS_PATH = "data/pooled_stats.md"
TARGET_CLEAN, TARGET_POISONED, TARGET_PER_ATTACK = 300, 300, 50


def _load(name, args):
    if name == "pds":
        from data.loaders.pds_local import load_pds_local_rows
        return load_pds_local_rows()
    if name == "bipia":
        from data.loaders.bipia import load_bipia_rows
        return load_bipia_rows(args.bipia_contexts, args.attacks_per_context, args.seed)
    if name == "poisonedrag":
        from data.loaders.poisonedrag import load_poisonedrag_rows
        return load_poisonedrag_rows("nq", args.prag_targets, args.seed, args.beir_zip)
    if name == "deepset":
        from data.loaders.deepset import load_deepset_rows
        return load_deepset_rows()
    if name == "opi":
        from data.loaders.opi import load_opi_rows
        return load_opi_rows(n=100)
    if name == "hackaprompt":
        from data.loaders.hackaprompt import load_hackaprompt_rows
        return load_hackaprompt_rows()
    raise ValueError(f"unknown source {name!r}")


def dedupe(rows):
    """Drop exact-duplicate texts; drop texts that appear with BOTH labels."""
    labels = defaultdict(set)
    for r in rows:
        labels[r.text.strip()].add(r.label)
    seen, kept, dup, conflict = set(), [], 0, 0
    for r in rows:
        key = r.text.strip()
        if len(labels[key]) > 1:
            conflict += 1
            continue
        if (key, r.label) in seen:
            dup += 1
            continue
        seen.add((key, r.label))
        kept.append(r)
    return kept, dup, conflict


def write_stats(rows, dup, conflict, path=STATS_PATH):
    n_clean = sum(1 for r in rows if r.label == 0)
    n_pois = len(rows) - n_clean
    L = ["# Pooled dataset statistics", "",
         "Generated by `python -m data.pool_datasets`. Do not edit by hand.", "",
         f"- Clean documents: **{n_clean}** (target >= {TARGET_CLEAN})",
         f"- Poisoned documents: **{n_pois}** (target >= {TARGET_POISONED})",
         f"- Exact duplicates removed: {dup}; texts with conflicting labels removed: {conflict}", "",
         "## Per source and label", "",
         "| source | label | n | median length | p25-p75 |", "|---|---|---|---|---|"]
    by = defaultdict(list)
    for r in rows:
        by[(r.source, r.label)].append(r)
    for (src, lab), rs in sorted(by.items()):
        n, med, p25, p75 = length_summary(rs)
        L.append(f"| {src} | {'poisoned' if lab else 'clean'} | {n} | {med} | {p25}-{p75} |")

    L += ["", "## Length-shortcut check", "",
          "If clean and poisoned documents of a source differ a lot in length, a detector "
          "can score well by measuring length alone. Ratio = poisoned median / clean median "
          "(flag if outside 0.5-2.0).", "",
          "| source | clean median | poisoned median | ratio | flag |", "|---|---|---|---|---|"]
    for src in sorted({r.source for r in rows}):
        c, p = by.get((src, 0), []), by.get((src, 1), [])
        if not c or not p:
            L.append(f"| {src} | {length_summary(c)[1] if c else '-'} | "
                     f"{length_summary(p)[1] if p else '-'} | - | one class only |")
            continue
        cm, pm = length_summary(c)[1], length_summary(p)[1]
        ratio = pm / cm if cm else float("inf")
        L.append(f"| {src} | {cm} | {pm} | {ratio:.2f} | {'**LENGTH SHORTCUT**' if not 0.5 <= ratio <= 2.0 else 'ok'} |")

    L += ["", "## Poisoned documents per attack type", "",
          f"| attack type | n | meets >= {TARGET_PER_ATTACK}? |", "|---|---|---|"]
    for t, n in sorted(Counter(r.attack_type for r in rows if r.label == 1).items()):
        L.append(f"| {t} | {n} | {'yes' if n >= TARGET_PER_ATTACK else 'no'} |")
    L.append("")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources", default="pds,bipia,poisonedrag,deepset")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--bipia-contexts", type=int, default=60, help="host docs per BIPIA task")
    ap.add_argument("--attacks-per-context", type=int, default=2)
    ap.add_argument("--prag-targets", type=int, default=40, help="PoisonedRAG targets (5 passages each)")
    ap.add_argument("--beir-zip", default=None, help="path to an already-downloaded BEIR nq.zip")
    args = ap.parse_args()

    rows = []
    for name in [s.strip() for s in args.sources.split(",") if s.strip()]:
        print(f"\n=== {name} ===")
        try:
            got = _load(name, args)
        except Exception as e:
            print(f"[{name}] SKIPPED: {type(e).__name__}: {e}")
            continue
        print_source_counts(got, name)
        rows += got

    if not rows:
        print("\nNothing loaded.")
        return
    rows, dup, conflict = dedupe(rows)
    ids = Counter(r.id for r in rows)
    clash = [i for i, c in ids.items() if c > 1]
    if clash:
        raise SystemExit(f"duplicate ids across sources, e.g. {clash[:3]}")

    write_jsonl(rows, POOLED_PATH)
    write_stats(rows, dup, conflict)
    n_clean = sum(1 for r in rows if r.label == 0)
    print(f"\nPooled {len(rows)} documents ({n_clean} clean / {len(rows) - n_clean} poisoned)")
    print(f"  -> {POOLED_PATH}\n  -> {STATS_PATH}")


if __name__ == "__main__":
    main()